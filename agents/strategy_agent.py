import json
from pathlib import Path
from datetime import datetime
from langchain_core.prompts import PromptTemplate
from tavily import TavilyClient
from config import get_llm, TAVILY_API_KEY
from schemas.campaign_schema import CampaignStrategyOutput
from schemas.research_schema import ResearchPlan
from schemas.product_schema import ProductAnalysisOutput
from schemas.audience_schema import AudienceAnalysisOutput

from prompts.strategy_prompt import (RESEARCH_PLANNER_PROMPT, CAMPAIGN_STRATEGY_PROMPT,)


# Project Root
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# LLM Setup
llm = get_llm(temperature=0)

# Tavily Setup
tavily_client = (TavilyClient(api_key=TAVILY_API_KEY)
    if TAVILY_API_KEY
    else None
)

# Brand Guidelines
guidelines_path = (PROJECT_ROOT / "data" / "Guidelines" / "brand_guidelines.md")

try:
    BRAND_GUIDELINES = guidelines_path.read_text(encoding="utf-8")
except FileNotFoundError:
    BRAND_GUIDELINES = ("No specific brand guidelines were provided.")

# Research Planner Chain
research_prompt = PromptTemplate(
    template=RESEARCH_PLANNER_PROMPT,
    input_variables=[
        "product_analysis", "audience_analysis",
        "campaign_information", "current_year",],
)

research_chain = (research_prompt | llm.with_structured_output(ResearchPlan))

# External Market Research
def search_market_insights(queries: list[str]) -> str:
    """
    Search the web using Tavily based on the queries
    generated by the Research Planner.

    Returns an empty string when external research
    is unavailable or no useful results are found.
    """

    if not tavily_client:
        print("⚠️ External market research unavailable: " "No Tavily API key found.")
        return ""

    research_results = []

    for query in queries:
        try:
            response = tavily_client.search(query=query, search_depth="advanced", max_results=2,)

            for result in response.get("results", []):
                title = result.get("title", "Unknown")
                url = result.get("url", "Unknown")
                content = result.get("content")

                if content:
                    # Limit the amount of external text
                    # passed to the strategy LLM.
                    content = content[:2000]

                    research_results.append(f"Title: {title}\n"f"Source: {url}\n"f"Content: {content}")

        except Exception as e:
            print(f"⚠️ Tavily search failed for "f"'{query}': {e}")

    if not research_results:
        print("⚠️ No relevant external market " "research was found.")
        return ""

    return "\n---\n".join(research_results)


# Campaign Strategy Chain
campaign_prompt = PromptTemplate(template=CAMPAIGN_STRATEGY_PROMPT,
    input_variables=[
        "product_analysis",
        "audience_analysis",
        "campaign_information",
        "brand_guidelines",
        "market_insights",
    ],
)

campaign_strategy_chain = (campaign_prompt | llm.with_structured_output(CampaignStrategyOutput))

# Main Campaign Strategy Agent
def create_campaign_strategy(product_analysis: ProductAnalysisOutput, audience_analysis: AudienceAnalysisOutput, campaign_information: dict,) -> CampaignStrategyOutput:
    """
    Build a campaign strategy using:
    1. Product analysis
    2. Audience analysis
    3. Campaign information
    4. External market research
    5. Brand guidelines
    """

# 1. Prepare Context
    product_context = (product_analysis.model_dump_json(indent=2))
    audience_context = (audience_analysis.model_dump_json(indent=2))
    campaign_context = json.dumps(campaign_information, ensure_ascii=False, indent=2)
    current_year = datetime.now().year

# 2. Plan External Research
    research_plan = research_chain.invoke({"product_analysis": product_context, "audience_analysis": audience_context, "campaign_information": campaign_context, "current_year": current_year,})


# 3. Search Current Market Insights
    market_insights = search_market_insights(research_plan.queries)

# 4. Generate Campaign Strategy
    strategy = campaign_strategy_chain.invoke({
        "product_analysis": product_context,
        "audience_analysis": audience_context,
        "campaign_information": campaign_context,
        "brand_guidelines": BRAND_GUIDELINES,
        "market_insights": market_insights,
    })

    return strategy